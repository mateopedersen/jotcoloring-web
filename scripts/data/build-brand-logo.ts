/** Rebuild the shared logo pixels from the approved 3D site logo, with a small ™. */
import sharp from 'sharp';
import fs from 'node:fs/promises';
import {deflateSync} from 'node:zlib';
const width=360,height=128;
const logo=await sharp('public/logo-3d.webp').resize(342,height,{fit:'fill'}).png().toBuffer();
const trademark=Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="360" height="128"><text x="342" y="50" font-family="Arial,sans-serif" font-weight="700" font-size="15" fill="#45414a">™</text></svg>');
const {data}=await sharp({create:{width,height,channels:3,background:'#fff'}}).composite([{input:logo,left:0,top:0},{input:trademark,left:0,top:0}]).removeAlpha().raw().toBuffer({resolveWithObject:true});
const compressed=deflateSync(data,{level:9});
await fs.writeFile('src/server/brand-logo.ts',`// Approved 3D JotColoring logo + trademark, RGB on white. Generated by build-brand-logo.ts.\nexport const BRAND_LOGO_WIDTH=${width};\nexport const BRAND_LOGO_HEIGHT=${height};\nexport const BRAND_LOGO_ZLIB='${compressed.toString('base64')}';\n`);
console.log(JSON.stringify({width,height,rgbBytes:data.length,compressedBytes:compressed.length}));
