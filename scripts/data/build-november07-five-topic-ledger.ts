function titleCase(value:string){
 const lowerWords=new Set(['a','an','and','as','at','by','for','in','of','on','or','the','to','with']);
 return value.split(/\s+/).filter(Boolean).map((word,index)=>index>0&&lowerWords.has(word.toLowerCase())?word.toLowerCase():word[0].toUpperCase()+word.slice(1)).join(' ');
}
function sourceSentence(sourceTopic:string,scene:string){
 const label:Record<string,string>={rhino:'Rhino',gymnastics:'Gymnastics','rescue-bots':'Transformers Rescue Bots',pusheen:'Pusheen',puppy:'Puppy'};
 return `${label[sourceTopic]} coloring page: ${scene[0].toUpperCase()+scene.slice(1)}.`;
}
function sourceObservationIndex(record:any){
 const number=record.number,level=String(record.webp?.path||'').match(/\/WebP\/([^/]+)\//)?.[1];
 // The reviewed contact sheets were assembled from the ZIP's level directories
 // in their directory order: EASY, HARD, MEDIUM, VERY-HARD. Rebind each note
 // to the filename number instead of assuming the contact-sheet cell is the
 // page number. This keeps the archival visual review tied to source pixels.
 if(level==='EASY'&&number>=1&&number<=25)return number-1;
 if(level==='HARD'&&number>=51&&number<=75)return 25+(number-51);
 if(level==='MEDIUM'&&number>=26&&number<=50)return 50+(number-26);
 if(level==='VERY-HARD'&&number>=76&&number<=100)return 75+(number-76);
 throw Error(`Unexpected source level/page order: ${record.webp?.path}`);
}
function makeMetadata(sourceTopic:string,record:any){
 const number=record.number,index=sourceObservationIndex(record);
 const entry=observationOverrides[sourceTopic]?.[number]??observations[sourceTopic][index];if(!entry)throw Error(`Missing inspected image description: ${sourceTopic} ${number}`);
 const [titleHint,scene]=entry.split('::');if(!titleHint||!scene)throw Error(`Invalid inspected image description: ${sourceTopic} ${number}`);
 const prefix=prefixes[sourceTopic],num=String(number).padStart(3,'0');
 const duplicatePrefix:Record<string,RegExp>={rhino:/^(?:rhino|rhinoceros)\s+/i,gymnastics:/^gymnastics\s+/i,pusheen:/^pusheen\s+/i,puppy:/^(?:puppy|dog)\s+/i};
 const cleanTitleHint=titleHint.replace(duplicatePrefix[sourceTopic]??/$^/,'');
 const title=`${prefix} ${titleCase(cleanTitleHint)} Coloring Page ${num}`;
 const description=sourceSentence(sourceTopic,scene);
 const alt=`Black-and-white ${searchable[sourceTopic]} coloring-page line art: ${scene}.`;
 return {title,description,alt_text:alt,scene};
}

